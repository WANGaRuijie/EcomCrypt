"""Generate the searchable venue registry and its human-readable catalog."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/venue_registry_v1.json"


def outputs():
    registry = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = registry["venues"]
    if len({row["id"] for row in rows}) != len(rows):
        raise ValueError("duplicate venue ID")
    module = "// Generated by python scripts/venues.py build.\nexport const registry = "
    module += json.dumps(rows, ensure_ascii=False, indent=2) + ";\n"
    groups = {}
    for row in rows:
        groups.setdefault(row["group"], []).append(row)
    lines = [
        "# EconCS × Blockchain venue 清单", "",
        f"{registry['updated_at']} 版本。共 {len(rows)} 个 venue 或发现渠道，分为 {len(groups)} 组。", "",
        "core 表示优先回填，targeted 表示结合主题和种子关系筛选。两者在月度流程中都放行，区别只影响排序。",
        "“加入”列标出 2026-11-08 新增的 venue；文末列出已拒收的 venue。修改 data/venue_registry_v1.json 后运行 python scripts/venues.py build。",
        "会议和工作坊必须有正式 proceedings；期刊按正式发表版本核实。",
        "预印本和工作论文已有正式会议或期刊版时不重复计数。", "",
        "SBC 等尚无正式 proceedings 证据的报告渠道不在本轮检索范围。",
        "[SBC 官方说明](https://www.sbc-conference.com/2026/)", "",
        "source_ids 需经索引核实才填写。空列表表示待解析。",
        "采集器使用 --venue ID 按完整名称解析 OpenAlex source，歧义结果进入覆盖报告。", "",
    ]
    kinds = {"conference": "会议", "journal": "期刊", "workshop": "工作坊",
             "program": "报告渠道", "repository": "预印本/索引", "working-paper": "工作论文"}
    for group, venues in groups.items():
        lines.extend([f"## {group}（{len(venues)}）", "", "| ID | 简称 | 完整名称 | 类型 | 检索优先级 | 加入 |",
                      "| --- | --- | --- | --- | --- | --- |"])
        for row in venues:
            name = f"[{row['name']}]({row['url']})" if row.get("url") else row["name"]
            lines.append(f"| {row['id']} | {row['label']} | {name} | {kinds[row['kind']]} | {row['priority']} | {'**' + row['added_at'] + ' 新增**' if row.get('added_at') else ''} |")
        lines.append("")
    denied = registry.get("denied_venues", [])
    if denied:
        lines.extend([f"## 已拒收（{len(denied)}）", "",
                      "按 `data/venue_policy_v2.json` 拒收；出版方级规则（MDPI、IEEE Access、Hindawi 等 DOI 前缀）同样适用于未列出的刊名。", "",
                      "| ID | 简称 | 完整名称 | 规则 |", "| --- | --- | --- | --- |"])
        for row in denied:
            lines.append(f"| {row['id']} | {row['label']} | {row['name']} | {row['denial_rule']} |")
        lines.append("")
    return {ROOT / "site/venue-registry.mjs": module, ROOT / "VENUES.md": "\n".join(lines) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("build", "check"))
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.mode == "check":
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale venue catalog: {path.name}")
        else:
            path.write_text(content, encoding="utf-8")
    print("Venue catalog and site registry are consistent.")


if __name__ == "__main__":
    main()
